import torch
import torchvision
from torchvision.models.detection import fasterrcnn_resnet50_fpn
from torchvision.models.detection.rpn import AnchorGenerator
from torchvision.transforms import transforms
from torch.utils.data import DataLoader


transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
])


trainset = torchvision.datasets.VOCDetection(root="data_small", year='2012', image_set='train', download=False, transform=transform)
testset = torchvision.datasets.VOCDetection(root="data_small", year='2012', image_set='val', download=False, transform=transform)


trainloader = DataLoader(trainset, batch_size=1, shuffle=True, num_workers=0)
testloader = DataLoader(testset, batch_size=1, shuffle=False, num_workers=0)


model = fasterrcnn_resnet50_fpn(weights=torchvision.models.detection.FasterRCNN_ResNet50_FPN_Weights.DEFAULT)


num_classes = 21
in_features = model.roi_heads.box_predictor.cls_score.in_features
model.roi_heads.box_predictor = torchvision.models.detection.faster_rcnn.FastRCNNPredictor(in_features, num_classes)


optimizer = torch.optim.SGD(model.parameters(), lr=0.005, momentum=0.9, weight_decay=0.0005)


num_epochs = 1
model.train()
for epoch in range(num_epochs):
    for i, data in enumerate(trainloader, 0):
        inputs, target = data
        optimizer.zero_grad()
        
        # Convert single VOC annotation to Faster R-CNN target format
        boxes = []
        labels = []
        for obj in target['annotation']['object']:
            bbox = obj['bndbox']
            boxes.append([float(bbox['xmin'][0]), float(bbox['ymin'][0]), 
                         float(bbox['xmax'][0]), float(bbox['ymax'][0])])
            # VOC class names to indices (simplified - using 1-20 for VOC classes)
            labels.append(1)  # Using label 1 for simplicity
        if len(boxes) == 0:
            # Handle empty annotations
            boxes = torch.zeros((0, 4), dtype=torch.float32)
            labels = torch.zeros((0,), dtype=torch.int64)
        else:
            boxes = torch.tensor(boxes, dtype=torch.float32)
            labels = torch.tensor(labels, dtype=torch.int64)
        formatted_target = {'boxes': boxes, 'labels': labels}
        
        # Forward pass with targets to compute losses
        loss_dict = model([inputs.squeeze(0)], [formatted_target])
        losses = sum(loss for loss in loss_dict.values())
        losses.backward()
        optimizer.step()

        if i % 50 == 49:
            print('[%d, %5d] loss: %.3f' % (epoch + 1, i + 1, losses.item()))

print('Finished Training')